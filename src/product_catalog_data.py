def validate_catalog_data():
    validate_product_families()

    expected_families = {
        family["family_id"]: family["product_count"]
        for family in PRODUCT_FAMILIES
    }

    assert set(PRODUCTS_BY_FAMILY) == set(expected_families), (
        "Les familles du catalogue ne correspondent pas à la configuration."
    )

    total = 0
    all_names = []

    for family_id, expected_count in expected_families.items():
        products = PRODUCTS_BY_FAMILY[family_id]

        assert len(products) == expected_count, (
            f"{family_id} : {len(products)} produits au lieu de "
            f"{expected_count}"
        )

        assert all(name.strip() for name in products), (
            f"{family_id} contient un nom vide."
        )

        assert len(set(products)) == len(products), (
            f"{family_id} contient des doublons."
        )

        total += len(products)
        all_names.extend(products)

        print(f"{family_id} : {len(products)} produits — OK")

    assert total == 1000, (
        f"Le catalogue doit contenir 1000 produits, trouvé : {total}"
    )

    assert len(set(all_names)) == len(all_names), (
        "Des noms identiques existent dans plusieurs familles."
    )

    print("--------------------------------")
    print("Catalogue valide : 6 familles, 1000 produits.")


if __name__ == "__main__":
    validate_catalog_data()
